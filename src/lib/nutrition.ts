import type { Goal } from "@/types";

export function getNutritionPlan(goal: Goal, weightKg?: number) {
  const w = weightKg ?? 80;
  if (goal === "Набрать мышечную массу") {
    return {
      title: "Базовый набор",
      proteinG: Math.round(w * 1.8),
      meals: 4,
      waterL: 3,
      rules: ["Белок в каждом приёме пищи", "Не пропускай завтрак в дни тренировок", "После тренировки — белок + углеводы в течение 2 часов", "Не охоться за идеальным меню. Охоться за повторяемостью"],
    };
  }
  if (goal === "Сбросить лишний вес и обрести форму") {
    return {
      title: "Рекомпозиция без драмы",
      proteinG: Math.round(w * 2.0),
      meals: 3,
      waterL: 3,
      rules: ["Белок высокий, объём еды — овощи", "Сладкое не запрещено — оно не ежедневно", "Вес на весах — не единственный сигнал", "Не режь калории в дни, когда уже сорвался на голод"],
    };
  }
  return {
    title: "Поддержание системы",
    proteinG: Math.round(w * 1.6),
    meals: 3,
    waterL: 2.5,
    rules: ["Белок в каждом приёме", "Вода 2.5+ л", "Один осознанный приём без телефона", "Алкоголь не чаще 1 раза в неделю, если цель — прогресс"],
  };
}
